// Generates the bundled Nuxt UI skill module from the vendored skill directory, so the platform's
// own coder agents apply the SAME text a local Claude Code session does.
//
// Why a generated module and not a runtime read: a bundled skill (ADR 0029) is deployment-static
// code shipped in `@cat-factory/agents`, and the Worker runtime forbids reading the filesystem at
// runtime. So the vendored `.claude/skills/nuxt-ui/` tree (the single authored source, from Slice
// 0) is inlined into a committed `*.generated.ts` module, imported as ordinary source — the same
// shape `precompile-prompts.mjs` uses for the prompt templates. Each markdown blob is emitted as a
// single-line JSON string, so the file stays tiny in LINE count (like `openapiDocument.generated.ts`)
// while carrying the whole ~120 KB of skill text.
//
// The `.claude/skills/nuxt-ui/` tree stays the ONLY hand-edited copy: this module is derived from
// it and `--check` fails CI if the two drift, so there is no second copy anyone maintains by hand.
//
//   Regenerate:  node scripts/generate-nuxt-ui-skill.mjs
//   Verify (CI): node scripts/generate-nuxt-ui-skill.mjs --check

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const SKILL_DIR = join(repoRoot, '.claude', 'skills', 'nuxt-ui')
const OUT_PATH = join(
  repoRoot,
  'backend',
  'packages',
  'agents',
  'src',
  'agents',
  'kinds',
  'nuxt-ui',
  'skill.generated.ts',
)

/**
 * Read a skill file as text, normalising CRLF to LF. The repo has no `.gitattributes`, so a
 * Windows checkout with autocrlf carries `\r\n` in the vendored `.md` files; without this the
 * frontmatter regex would miss and the embedded content would diverge from the LF the committed
 * module (and CI, on Linux) produces, reddening `--check`.
 */
function readSkillText(pathAbs) {
  return readFileSync(pathAbs, 'utf8').replace(/\r\n/g, '\n')
}

/** Every file under the skill dir, relative to it, POSIX-slashed, in a stable sorted order. */
function skillFiles(dirAbs) {
  const out = []
  for (const entry of readdirSync(dirAbs)) {
    const abs = join(dirAbs, entry)
    if (statSync(abs).isDirectory()) out.push(...skillFiles(abs))
    else out.push(relative(SKILL_DIR, abs).replaceAll('\\', '/'))
  }
  return out.sort()
}

/**
 * Split a `SKILL.md` into its frontmatter `name`/`description` and its markdown body. Normalises
 * CRLF up front so the result is LF-only regardless of how the caller read the file (a Windows
 * checkout carries `\r\n`; the repo has no `.gitattributes` to force LF).
 */
export function parseSkillMd(text) {
  text = text.replace(/\r\n/g, '\n')
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text)
  if (!match) throw new Error('.claude/skills/nuxt-ui/SKILL.md: missing YAML frontmatter')
  const [, frontmatter, body] = match
  const field = (key) => {
    const line = frontmatter.split('\n').find((l) => l.startsWith(`${key}:`))
    if (!line) throw new Error(`.claude/skills/nuxt-ui/SKILL.md: frontmatter missing '${key}'`)
    return line.slice(key.length + 1).trim()
  }
  return { name: field('name'), description: field('description'), body: body.replace(/\s+$/, '') }
}

export function buildModule() {
  const files = skillFiles(SKILL_DIR)
  const skill = parseSkillMd(readSkillText(join(SKILL_DIR, 'SKILL.md')))
  const resources = files
    .filter((rel) => rel !== 'SKILL.md')
    .map((rel) => ({ relPath: rel, content: readSkillText(join(SKILL_DIR, rel)) }))

  const lines = [
    '// GENERATED by scripts/generate-nuxt-ui-skill.mjs from .claude/skills/nuxt-ui/. DO NOT EDIT.',
    '// Regenerate after editing the vendored skill: node scripts/generate-nuxt-ui-skill.mjs',
    '',
    `export const NUXT_UI_SKILL_NAME = ${JSON.stringify(skill.name)}`,
    `export const NUXT_UI_SKILL_DESCRIPTION = ${JSON.stringify(skill.description)}`,
    `export const NUXT_UI_SKILL_INSTRUCTIONS = ${JSON.stringify(skill.body)}`,
    '',
    'export const NUXT_UI_SKILL_RESOURCES: { relPath: string; content: string }[] = [',
    ...resources.map(
      (r) => `  { relPath: ${JSON.stringify(r.relPath)}, content: ${JSON.stringify(r.content)} },`,
    ),
    ']',
    '',
  ]
  return lines.join('\n')
}

function main() {
  const generated = buildModule()

  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT_PATH, 'utf8')
    } catch {
      // Falls through to the mismatch report below.
    }
    if (current !== generated) {
      console.error(
        `${relative(repoRoot, OUT_PATH)} is out of date with .claude/skills/nuxt-ui/.\n` +
          'Regenerate it: node scripts/generate-nuxt-ui-skill.mjs',
      )
      process.exit(1)
    }
    console.log('nuxt-ui skill module is up to date.')
  } else {
    writeFileSync(OUT_PATH, generated)
    console.log(`Wrote ${relative(repoRoot, OUT_PATH)}`)
  }
}

// Only run the CLI when invoked directly, so the sibling test can import the pure helpers
// (`parseSkillMd`, `buildModule`) with no read/write side effect.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
