// Java emitter: `sdk/java/src/main/java/ai/catfactory/sdk/model/*.java` + the resource clients.
//
// ---------------------------------------------------------------------------------------------
// ONE artifact, consumable idiomatically from BOTH Java and Kotlin. No second SDK.
// ---------------------------------------------------------------------------------------------
//
// A Kotlin-specific SDK cannot be produced by "adding metadata" to a Java jar: Kotlin's own
// metadata (`@Metadata`) is emitted by the Kotlin compiler and describes Kotlin declarations —
// it cannot be synthesised for Java sources, and forging it would produce a jar the Kotlin
// compiler mis-reads rather than one it understands. What CAN be added is the metadata Kotlin
// actually READS from a Java library, and doing so removes essentially every reason to maintain
// a separate Kotlin client. Six choices below, each because of a specific Kotlin failure mode:
//
//   1. **JSpecify nullness** (`@NullMarked` on the package, `@Nullable` per component). Without
//      it, Kotlin sees every Java reference as a PLATFORM type (`String!`) — the compiler stops
//      enforcing null-safety, and an NPE surfaces at the first dereference instead of at the
//      call. With it, `task.status()` is `TaskStatus` and `task.pullRequestUrl()` is `String?`,
//      which is exactly what a hand-written Kotlin client would give.
//   2. **Kotlin hard keywords are escaped.** `PublicPipeline.public` is a wire field whose name
//      is a keyword in BOTH languages: it cannot be a Java record component at all, and in
//      Kotlin it would need backticks at every use site. It becomes `isPublic()` with an
//      explicit `@JsonProperty("public")`, so both languages read naturally and the wire name is
//      untouched.
//   3. **Builders, not constructor overloads or default parameters.** Kotlin cannot see Java
//      default parameter values (Java has none) and a telescoping-constructor set is unpleasant
//      from both sides. Every request model gets a builder, which reads well in Java and is
//      directly usable from Kotlin's `apply { }`.
//   4. **Unchecked exceptions only.** Kotlin has no checked exceptions, so a `throws IOException`
//      on the public surface would be invisible to a Kotlin caller and force `try`/`catch`
//      ceremony on the Java one. Every failure is an unchecked `CatFactoryException`.
//   5. **A sealed error hierarchy**, so a Kotlin caller can `when` over the failure classes
//      exhaustively rather than testing status codes by hand.
//   6. **`CompletableFuture` for the async surface**, which `kotlinx-coroutines-jdk8`'s
//      `.await()` turns into a suspending call — so Kotlin gets coroutines without this artifact
//      depending on the Kotlin runtime, and a Java caller is not handed a Kotlin `Continuation`.
//
// The residual gap is stated honestly in sdk/java/README.md: a Kotlin caller does not get
// `data class` niceties (`copy()`, destructuring) on the models, and named arguments do not work
// on Java methods. Both are cosmetic next to null-safety, and neither is worth a second artifact
// that would have to be kept in step release for release.

import { pascal } from './ir.mjs'
import { GROUP_DOCS, GROUPS, groupOperations } from './surface.mjs'

const PACKAGE = 'ai.catfactory.sdk'
const MODEL_PACKAGE = `${PACKAGE}.model`
const RESOURCE_PACKAGE = `${PACKAGE}.resources`
const MODEL_DIR = 'src/main/java/ai/catfactory/sdk/model'
// The generated tree is two whole PACKAGES the generator owns outright, so a type the spec drops
// is deleted rather than left behind compiling. Every hand-written file lives in `ai.catfactory.sdk`
// itself, which the generator never touches.
const RESOURCE_DIR = 'src/main/java/ai/catfactory/sdk/resources'

const BANNER = `// GENERATED by \`pnpm gen:sdk\` from docs/openapi.json — DO NOT EDIT BY HAND.
// Regenerate after any change to the \`/api/v1\` contracts; \`pnpm check:sdk\` fails CI on drift.
`

/**
 * Reserved words in Java, PLUS Kotlin's HARD keywords.
 *
 * The Kotlin half is the point of this set: a Java member named `object`, `fun`, `val`, `is`,
 * `in` or `when` compiles fine and is legal to call from Java, but a Kotlin caller has to
 * backtick it at every use site. Escaping here costs the Java user nothing (the wire name is
 * preserved by an explicit `@JsonProperty`) and saves the Kotlin user a papercut on every line.
 */
