// Gatekeeper-bindings emitter: `sdk/gatekeeper/src/bindings.generated.ts`.
//
// The sixth thing rendered from the one IR, and like the MCP facade it is not a client: it emits
// a POLICY-ANNOTATED OPERATION TABLE for credential-holding front-ends (the Cloudflare OS
// Gatekeeper pattern: a Worker that owns the API key and exposes typed capabilities to agents;
// see `docs/initiatives/cloudflare-os-gatekeeper.md`). Each entry carries what such a front-end
// needs to enforce and audit a call without hand-curating anything: the key-scope floor the route
// enforces (`minScope`, from the spec's `x-min-scope`), whether the call mutates, how the result
// comes back (value / stream / binary), the consequence hints shared with the MCP table, and an
// `invoke` thunk onto `@cat-factory/sdk` using the SAME flattened-argument convention as the MCP
// facade, so the two projections agree about what a call looks like.
//
// Generating the table buys the property every projection here exists for: an endpoint added to
// the contracts cannot ship as a hole in the policy table, and a scope floor changed in the
// contracts cannot drift from what a Gatekeeper enforces.
//
// Unlike MCP there is NO omission table: a binding is metadata plus a thunk, so a streaming or
// binary operation is representable and ships with its `result` kind stated. What IS enforced:
// every operation's `minScope` must be a member of the ladder below, so a rung added to
// `PUBLIC_API_SCOPES` (contracts) fails generation here until the ladder gains it, and the
// published helpers move in the same diff.

import { snake } from './ir.mjs'
import { GROUPS, MCP_TOOL_HINTS, groupOperations } from './surface.mjs'

const BANNER = `// GENERATED by \`pnpm gen:sdk\` from docs/openapi.json — DO NOT EDIT BY HAND.
// Regenerate after any change to the \`/api/v1\` contracts; \`pnpm check:sdk\` fails CI on drift.
`

/**
 * The scope ladder, least to greatest, as `backend/docs/public-api.md` documents it. Restated
 * here (a published package sees the spec alone, and OpenAPI's bearer scheme has no scope slot)
 * and held honest by the assertion in {@link assertScopesOnLadder}: an operation declaring a rung
 * this list lacks fails generation, so the ladder cannot silently fall behind the contracts'
 * `PUBLIC_API_SCOPES`.
 */
const SCOPE_LADDER = ['read', 'write', 'decide', 'admin']

/** A single-quoted TS string literal (same escaping as the MCP emitter's). */
function lit(value) {
  return `'${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')}'`
}

/** The binding name a policy file addresses: `<group>_<method>`, the MCP tool's own spelling. */
function bindingName(operation) {
  return `${snake(operation.group)}_${snake(operation.method)}`
}

/** How the operation's success body comes back to a caller of `invoke`. */
function resultKind(operation) {
  if (operation.stream) return 'stream'
  if (operation.binary) return 'binary'
  return 'value'
}

/**
 * The SDK call this binding forwards to (the MCP emitter's convention verbatim): path params as
 * positional strings, the body under `args.body`, query keys picked BY NAME so a caller's typo
 * cannot ride along as a filter that silently did nothing.
 */
function invocation(operation) {
  const bodyType = `Parameters<CatFactoryClient[${lit(operation.group)}][${lit(operation.method)}]>[${operation.pathParams.length}]`
  const args = [
    ...operation.pathParams.map((param) => `str(args, ${lit(param.wireName)})`),
    operation.body ? `args.body as ${bodyType}` : null,
    operation.queryParams.length > 0
      ? `pick(args, QUERY_${snake(bindingName(operation)).toUpperCase()})`
      : null,
  ].filter(Boolean)
  return `client.${operation.group}.${operation.method}(${args.join(', ')})`
}

function assertScopesOnLadder(placed) {
  for (const operation of placed) {
    if (!SCOPE_LADDER.includes(operation.minScope)) {
      throw new Error(
        `Gatekeeper: operation '${operation.id}' declares minScope '${operation.minScope}', which ` +
          'SCOPE_LADDER (scripts/sdk/emit-gatekeeper.mjs) does not know. If the contracts gained a ' +
          'rung, add it here in ladder position so the published helpers keep ranking correctly.',
      )
    }
  }
}

function emitBinding(operation) {
  const query =
    operation.queryParams.length > 0
      ? `const QUERY_${snake(bindingName(operation)).toUpperCase()} = [${operation.queryParams
          .map((param) => lit(param.wireName))
          .join(', ')}] as const\n`
      : ''
  const hints = MCP_TOOL_HINTS[operation.id]
  const binding =
    `  {\n` +
    `    name: ${lit(bindingName(operation))},\n` +
    `    group: ${lit(operation.group)},\n` +
    `    method: ${lit(operation.method)},\n` +
    `    operationId: ${lit(operation.id)},\n` +
    `    httpMethod: ${lit(operation.httpMethod)},\n` +
    `    path: ${lit(operation.path)},\n` +
    `    summary: ${lit(operation.summary)},\n` +
    `    minScope: ${lit(operation.minScope)},\n` +
    `    readOnly: ${operation.httpMethod === 'GET'},\n` +
    `    result: ${lit(resultKind(operation))},\n` +
    (hints ? `    consequence: ${JSON.stringify(hints)},\n` : '') +
    `    pathParams: [${operation.pathParams.map((p) => lit(p.wireName)).join(', ')}],\n` +
    `    queryParams: ${
      operation.queryParams.length > 0
        ? `QUERY_${snake(bindingName(operation)).toUpperCase()}`
        : '[]'
    },\n` +
    `    hasBody: ${Boolean(operation.body)},\n` +
    `    invoke: (client, args) => ${invocation(operation)},\n` +
    `  },\n`
  return { query, binding }
}

function emitBindings(ir, placed) {
  assertScopesOnLadder(placed)
  const ordered = GROUPS.flatMap((group) => groupOperations(placed, group))
  const emitted = ordered.map((operation) => emitBinding(operation))

  return `${BANNER}
// The policy-annotated operation table: one entry per \`/api/v1\` operation, surface version ${ir.info.version}.
//
// Each entry is what a credential-holding front-end (a Cloudflare OS Gatekeeper, or any proxy
// that owns the key and meters what callers may do) needs to enforce, audit and forward a call:
// the scope floor the route enforces, whether it mutates, how the result comes back, and a thunk
// onto \`@cat-factory/sdk\`. Nothing here decides retry, auth, error mapping or encoding: the SDK
// does. The argument convention is the MCP facade's, so the two projections describe one call
// shape.

import type { CatFactoryClient } from '@cat-factory/sdk'

/**
 * A public-API key scope. The ladder is INCLUSIVE and ordered
 * (${SCOPE_LADDER.join(' < ')}): a key satisfies every floor at or below its own rung. See
 * \`backend/docs/public-api.md\`, "Pick the right scope".
 */
export type PublicApiScope = ${SCOPE_LADDER.map((s) => lit(s)).join(' | ')}

/** The scope ladder, least to greatest. The ARRAY ORDER is the ranking. */
export const PUBLIC_API_SCOPE_LADDER: readonly PublicApiScope[] = [${SCOPE_LADDER.map((s) =>
    lit(s),
  ).join(', ')}]

/** One \`/api/v1\` operation, as a policy-annotated capability. */
export interface GatekeeperBinding {
  /** The name a policy file addresses, \`<group>_<method>\`: the MCP tool's own spelling. */
  name: string
  /** The SDK resource group, spelled as the TypeScript client mounts it (\`client.taskTypes\`). */
  group: string
  /** The method on that resource client. */
  method: string
  /** The spec's \`operationId\`, for correlating a forwarded call with a deployment's logs. */
  operationId: string
  httpMethod: string
  /** The route, with \`{param}\` placeholders. */
  path: string
  /** One-line label from the spec's \`summary\`. */
  summary: string
  /**
   * The least key scope the route admits: the STATIC floor the deployment enforces, and only
   * that: a run-starting operation can still be refused \`pipeline_requires_decide_scope\` at
   * request time when the named pipeline can park on a human.
   */
  minScope: PublicApiScope
  /** Whether the call changes nothing (a GET). */
  readOnly: boolean
  /**
   * How \`invoke\`'s result comes back: a decoded \`value\`, an SSE \`stream\` reader, or raw
   * \`binary\` bytes. A front-end that only relays JSON should route \`stream\`/\`binary\`
   * bindings specially or withhold them, stating which.
   */
  result: 'value' | 'stream' | 'binary'
  /**
   * The annotations the HTTP method cannot supply, present only where the consequence is real
   * money or a merged pull request (shared with the MCP table's hints). Absent means the cautious
   * reading applies: treat an unannotated mutation as destructive and non-idempotent.
   */
  consequence?: { destructive: boolean; idempotent: boolean }
  /** Path parameter names \`invoke\` reads from \`args\`, in path order. */
  pathParams: readonly string[]
  /** Query parameter names \`invoke\` forwards from \`args\`; anything else is dropped. */
  queryParams: readonly string[]
  /** Whether \`invoke\` reads \`args.body\` as the request body. */
  hasBody: boolean
  /** Forward a call to the SDK: path params and query keys at the top level, body under \`body\`. */
  invoke: (client: CatFactoryClient, args: Record<string, unknown>) => Promise<unknown>
}

/** Read a required string argument, failing with the parameter's own name. */
function str(args: Record<string, unknown>, name: string): string {
  const value = args[name]
  if (typeof value !== 'string' || value.length === 0) {
    throw new TypeError(\`\${name} is required and must be a non-empty string\`)
  }
  return value
}

/** The subset of \`args\` that belongs in the query string, picked by name. */
function pick(
  args: Record<string, unknown>,
  names: readonly string[],
): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  for (const name of names) {
    if (args[name] !== undefined) out[name] = args[name]
  }
  return out
}

${emitted
  .map((entry) => entry.query)
  .filter(Boolean)
  .join('')}
/** Every \`/api/v1\` operation as a policy-annotated binding, in resource-group order. */
export const GATEKEEPER_BINDINGS: readonly GatekeeperBinding[] = [
${emitted.map((entry) => entry.binding).join('')}]
`
}

/** Every generated file for the gatekeeper bindings, keyed by path within `sdk/gatekeeper/`. */
export function emit(ir, placed) {
  return {
    'src/bindings.generated.ts': emitBindings(ir, placed),
  }
}
