// Gatekeeper-bindings emitter: `sdk/gatekeeper/src/bindings.generated.ts`.
//
// The sixth thing rendered from the one IR, and like the MCP facade it is not a client: it emits
// a POLICY-ANNOTATED OPERATION TABLE for credential-holding front-ends (the Cloudflare OS
// Gatekeeper pattern: a Worker that owns the API key and exposes typed capabilities to agents;
// see `docs/initiatives/cloudflare-os-gatekeeper.md`). Each entry carries what such a front-end
// needs to enforce and audit a call without hand-curating anything: the key-scope floor the route
// enforces (`minScope`, from the spec's `x-min-scope`), whether the call mutates, how the result
// comes back (value / stream / binary), the consequence hints shared with the MCP table, and an
// `invoke` thunk onto `@cat-factory/sdk` using the SAME flattened-argument convention as the MCP
// facade, so the two projections agree about what a call looks like.
//
// Generating the table buys the property every projection here exists for: an endpoint added to
// the contracts cannot ship as a hole in the policy table, and a scope floor changed in the
// contracts cannot drift from what a Gatekeeper enforces.
//
// Unlike MCP there is NO omission table: a binding is metadata plus a thunk, so a streaming or
// binary operation is representable and ships with its `result` kind stated.
//
// The scope ladder this publishes is READ OFF THE SPEC (`x-public-api-scopes`, stamped from the
// contracts' `PUBLIC_API_SCOPES`), never restated here. A restated copy passes generation while
// it is merely INCOMPLETE — nothing forces an operation to exercise every rung — and the damage
// lands on a consumer instead: an unknown rung ranks -1, so `bindingsWithinScope` hands back an
// empty table and a key at the new rung reads as a key with no permissions.

import { snake } from './ir.mjs'
import { DEBUG_TELEMETRY_SINKS, GROUPS, MCP_TOOL_HINTS, groupOperations } from './surface.mjs'

/** The sink names a binding may declare, in the order the run overview reports them. */
const TELEMETRY_SINKS = [
  'llmCalls',
  'agentContext',
  'searchQueries',
  'toolCalls',
  'provisioningLog',
]

const BANNER = `// GENERATED by \`pnpm gen:sdk\` from docs/openapi.json — DO NOT EDIT BY HAND.
// Regenerate after any change to the \`/api/v1\` contracts; \`pnpm check:sdk\` fails CI on drift.
`

/** A single-quoted TS string literal (same escaping as the MCP emitter's). */
function lit(value) {
  return `'${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')}'`
}

/** The binding name a policy file addresses: `<group>_<method>`, the MCP tool's own spelling. */
function bindingName(operation) {
  return `${snake(operation.group)}_${snake(operation.method)}`
}

/** How the operation's success body comes back to a caller of `invoke`. */
function resultKind(operation) {
  if (operation.stream) return 'stream'
  if (operation.binary) return 'binary'
  return 'value'
}

/**
 * The SDK call this binding forwards to (the MCP emitter's convention verbatim): path params as
 * positional strings, the body under `args.body`, query keys picked BY NAME so a caller's typo
 * cannot ride along as a filter that silently did nothing.
 */
function invocation(operation) {
  const bodyType = `Parameters<CatFactoryClient[${lit(operation.group)}][${lit(operation.method)}]>[${operation.pathParams.length}]`
  const args = [
    ...operation.pathParams.map((param) => `str(args, ${lit(param.wireName)})`),
    operation.body ? `args.body as ${bodyType}` : null,
    operation.queryParams.length > 0
      ? `pick(args, QUERY_${snake(bindingName(operation)).toUpperCase()})`
      : null,
  ].filter(Boolean)
  return `client.${operation.group}.${operation.method}(${args.join(', ')})`
}

/**
 * Refuse a spec whose own halves disagree: an operation whose floor is not a member of the
 * vocabulary the same document publishes. Both halves come from the contracts, so this is not the
 * drift guard (that job belongs to deriving the ladder rather than restating it); it is the
 * totality guard for the values `generate-openapi.mjs` stamps by HAND onto the contract-less raw
 * routes, which no type checks.
 */
function assertScopesOnLadder(placed, ladder) {
  for (const operation of placed) {
    if (!ladder.includes(operation.minScope)) {
      throw new Error(
        `Gatekeeper: operation '${operation.id}' declares minScope '${operation.minScope}', which ` +
          `is not on the spec's own x-public-api-scopes ladder (${ladder.join(' < ')}). A raw ` +
          "route's hand-written 'x-min-scope' in scripts/generate-openapi.mjs is the usual cause.",
      )
    }
  }
}

/**
 * Refuse a spec whose `/debug` reads are not each classified as carrying captured telemetry or
 * not (see {@link DEBUG_TELEMETRY_SINKS}).
 *
 * Total in BOTH directions, because either gap is silent in its own way: an unclassified read
 * ships as a capability no derived policy denies, and a stale entry is a deny rule that stopped
 * matching anything the moment the operation was renamed. Neither shows up as an error at the
 * deployment; both show up as a read-only tier that can page a run's transcript.
 */
function assertTelemetryClassified(placed) {
  const debugIds = new Set(
    placed.filter((operation) => operation.group === 'debug').map((operation) => operation.id),
  )
  for (const id of debugIds) {
    if (!(id in DEBUG_TELEMETRY_SINKS)) {
      throw new Error(
        `Gatekeeper: debug operation '${id}' is not classified in DEBUG_TELEMETRY_SINKS ` +
          '(scripts/sdk/surface.mjs). Name the telemetry sink it reads, or null when it carries ' +
          'no captured text: an unclassified read joins no derived deny list, so a read-only ' +
          'policy tier would serve it beside the siblings it withholds.',
      )
    }
  }
  for (const [id, sink] of Object.entries(DEBUG_TELEMETRY_SINKS)) {
    if (!debugIds.has(id)) {
      throw new Error(
        `Gatekeeper: DEBUG_TELEMETRY_SINKS names '${id}', which the spec's debug group no ` +
          'longer has.',
      )
    }
    if (sink !== null && !TELEMETRY_SINKS.includes(sink)) {
      throw new Error(
        `Gatekeeper: DEBUG_TELEMETRY_SINKS gives '${id}' the sink '${sink}', which is not one ` +
          `of ${TELEMETRY_SINKS.join(', ')}.`,
      )
    }
  }
}

function emitBinding(operation) {
  const query =
    operation.queryParams.length > 0
      ? `const QUERY_${snake(bindingName(operation)).toUpperCase()}: readonly GatekeeperQueryParam[] = [\n${operation.queryParams
          .map(
            (param) =>
              `  { name: ${lit(param.wireName)}, required: ${Boolean(param.required)} },\n`,
          )
          .join('')}]\n`
      : ''
  const hints = MCP_TOOL_HINTS[operation.id]
  const binding =
    `  {\n` +
    `    name: ${lit(bindingName(operation))},\n` +
    `    group: ${lit(operation.group)},\n` +
    `    method: ${lit(operation.method)},\n` +
    `    operationId: ${lit(operation.id)},\n` +
    `    httpMethod: ${lit(operation.httpMethod)},\n` +
    `    path: ${lit(operation.path)},\n` +
    `    summary: ${lit(operation.summary)},\n` +
    `    minScope: ${lit(operation.minScope)},\n` +
    `    readOnly: ${operation.httpMethod === 'GET'},\n` +
    `    result: ${lit(resultKind(operation))},\n` +
    (hints ? `    consequence: ${JSON.stringify(hints)},\n` : '') +
    (DEBUG_TELEMETRY_SINKS[operation.id]
      ? `    telemetrySink: ${lit(DEBUG_TELEMETRY_SINKS[operation.id])},\n`
      : '') +
    `    pathParams: [${operation.pathParams.map((p) => lit(p.wireName)).join(', ')}],\n` +
    `    queryParams: ${
      operation.queryParams.length > 0
        ? `QUERY_${snake(bindingName(operation)).toUpperCase()}`
        : '[]'
    },\n` +
    `    hasBody: ${Boolean(operation.body)},\n` +
    // `async` is load-bearing, not style: `str()` throws SYNCHRONOUSLY on a missing path
    // parameter, and a policy layer forwarding an untrusted argument bag reaches that case
    // routinely. A bare arrow would throw past the `Promise` this is typed as, so a caller's
    // `.catch()` would not see it; `async` makes the one failure mode a rejection like every
    // other.
    `    invoke: async (client, args) => ${invocation(operation)},\n` +
    `  },\n`
  return { query, binding }
}

function emitBindings(ir, placed) {
  const SCOPE_LADDER = ir.scopeLadder
  assertScopesOnLadder(placed, SCOPE_LADDER)
  assertTelemetryClassified(placed)
  const ordered = GROUPS.flatMap((group) => groupOperations(placed, group))
  const emitted = ordered.map((operation) => emitBinding(operation))

  return `${BANNER}
// The policy-annotated operation table: one entry per \`/api/v1\` operation, surface version ${ir.info.version}.
//
// Each entry is what a credential-holding front-end (a Cloudflare OS Gatekeeper, or any proxy
// that owns the key and meters what callers may do) needs to enforce, audit and forward a call:
// the scope floor the route enforces, whether it mutates, how the result comes back, and a thunk
// onto \`@cat-factory/sdk\`. Nothing here decides retry, auth, error mapping or encoding: the SDK
// does. The argument convention is the MCP facade's, so the two projections describe one call
// shape.

import type { CatFactoryClient } from '@cat-factory/sdk'

/**
 * A public-API key scope. The ladder is INCLUSIVE and ordered
 * (${SCOPE_LADDER.join(' < ')}): a key satisfies every floor at or below its own rung. See
 * \`backend/docs/public-api.md\`, "Pick the right scope".
 */
export type PublicApiScope = ${SCOPE_LADDER.map((s) => lit(s)).join(' | ')}

/**
 * The scope ladder, least to greatest. The ARRAY ORDER is the ranking, and this is the
 * deployment's own vocabulary: generated from the spec's \`x-public-api-scopes\`, which the
 * server stamps from the same constant its admission check ranks with.
 */
export const PUBLIC_API_SCOPE_LADDER: readonly PublicApiScope[] = [${SCOPE_LADDER.map((s) =>
    lit(s),
  ).join(', ')}]

/**
 * A store of captured run telemetry: the five sinks the platform records a run's model, tool,
 * search and provisioning activity into, and the five the run overview reports on.
 */
export type TelemetrySink = ${TELEMETRY_SINKS.map((sink) => lit(sink)).join(' | ')}

/** One query parameter of a binding, and whether the deployment insists on it. */
export interface GatekeeperQueryParam {
  /** The wire name: the query-string key, and the key \`invoke\` reads it from \`args\` under. */
  name: string
  /**
   * True when omitting it is a 400 rather than an unfiltered read. \`invoke\` refuses such a
   * call locally, naming the parameter, instead of forwarding a request that cannot succeed.
   */
  required: boolean
}

/** One \`/api/v1\` operation, as a policy-annotated capability. */
export interface GatekeeperBinding {
  /** The name a policy file addresses, \`<group>_<method>\`: the MCP tool's own spelling. */
  name: string
  /** The SDK resource group, spelled as the TypeScript client mounts it (\`client.taskTypes\`). */
  group: string
  /** The method on that resource client. */
  method: string
  /** The spec's \`operationId\`, for correlating a forwarded call with a deployment's logs. */
  operationId: string
  httpMethod: string
  /** The route, with \`{param}\` placeholders. */
  path: string
  /** One-line label from the spec's \`summary\`. */
  summary: string
  /**
   * The least key scope the route admits: the STATIC floor the deployment enforces, and only
   * that: a run-starting operation can still be refused \`pipeline_requires_decide_scope\` at
   * request time when the named pipeline can park on a human.
   */
  minScope: PublicApiScope
  /** Whether the call changes nothing (a GET). */
  readOnly: boolean
  /**
   * How \`invoke\`'s result comes back: a decoded \`value\`, an SSE \`stream\` reader, or raw
   * \`binary\` bytes. A front-end that only relays JSON should route \`stream\`/\`binary\`
   * bindings specially or withhold them, stating which.
   */
  result: 'value' | 'stream' | 'binary'
  /**
   * The annotations the HTTP method cannot supply, present only where the consequence is real
   * money or a merged pull request (shared with the MCP table's hints). Absent means the cautious
   * reading applies: treat an unannotated mutation as destructive and non-idempotent.
   */
  consequence?: { destructive: boolean; idempotent: boolean }
  /**
   * The run-telemetry sink this call reads rows from, when it reads one.
   *
   * Present ONLY on the operations that serve captured text: model prompts and replies, tool
   * arguments and results, agent search terms, provisioning command output. Absent on every
   * other operation, including the run-level diagnostics that project a run's lifecycle and
   * aggregates without any of it.
   *
   * It is here because it is the one policy fact neither \`minScope\` nor \`readOnly\` can
   * carry: all of this sits inside a \`read\` key's floor, since reading it is a read, so a
   * tier meant for oversight has to withhold these operations by name. See
   * {@link TELEMETRY_BINDINGS}, which is that list, derived.
   */
  telemetrySink?: TelemetrySink
  /**
   * Path parameter names \`invoke\` reads from \`args\`, in path order. Every one is required
   * by construction: a path with a hole in it is not a route.
   */
  pathParams: readonly string[]
  /**
   * Query parameters \`invoke\` forwards from \`args\`; anything else is dropped.
   *
   * Records rather than bare names because REQUIREDNESS is the half a front-end cannot infer:
   * a query parameter usually means "narrow this", and the one that means "say which question
   * you are asking" is indistinguishable from it by name. Without this a front-end rendering a
   * form or validating an argument bag has no way to refuse the call the deployment will
   * refuse, and forwards it to collect a 400 instead.
   */
  queryParams: readonly GatekeeperQueryParam[]
  /** Whether \`invoke\` reads \`args.body\` as the request body. */
  hasBody: boolean
  /**
   * Forward a call to the SDK: path params and query keys at the top level, body under \`body\`.
   *
   * Every failure is a REJECTION, the SDK's own and a missing-argument \`TypeError\` alike, so one
   * \`.catch()\` (or one \`try\` around an \`await\`) covers a forwarded call.
   */
  invoke: (client: CatFactoryClient, args: Record<string, unknown>) => Promise<unknown>
}

/** Read a required string argument, failing with the parameter's own name. */
function str(args: Record<string, unknown>, name: string): string {
  const value = args[name]
  if (typeof value !== 'string' || value.length === 0) {
    throw new TypeError(\`\${name} is required and must be a non-empty string\`)
  }
  return value
}

/**
 * The subset of \`args\` that belongs in the query string, picked by name.
 *
 * Returns the call site's own query type, and EARNS that narrowing rather than asserting it:
 * every required parameter is checked present first, so the object handed back satisfies the
 * shape the SDK method declares. Without the check the assertion was a claim about a bag that
 * had just been allowed to drop the one field the deployment insists on, and the failure
 * surfaced as a 400 from a call that never had to be made.
 *
 * PRESENCE is the whole check, deliberately. What a value may BE is the deployment's judgement
 * (a closed vocabulary, a numeric range, a length), it is stated in the spec these bindings are
 * generated from, and its refusal already names the field. Re-deriving it here would be a
 * second copy of the contract, free to disagree with the first.
 */
function pick<Query>(args: Record<string, unknown>, params: readonly GatekeeperQueryParam[]): Query {
  const out: Record<string, unknown> = {}
  for (const param of params) {
    const value = args[param.name]
    if (value === undefined) {
      if (param.required) {
        throw new TypeError(\`\${param.name} is required\`)
      }
      continue
    }
    out[param.name] = value
  }
  return out as Query
}

${emitted
  .map((entry) => entry.query)
  .filter(Boolean)
  .join('')}
/** Every \`/api/v1\` operation as a policy-annotated binding, in resource-group order. */
export const GATEKEEPER_BINDINGS: readonly GatekeeperBinding[] = [
${emitted.map((entry) => entry.binding).join('')}]

/**
 * Every binding that reads a run-telemetry sink: the operations that serve CAPTURED TEXT.
 *
 * Published so a policy can withhold them as a set. Every one is within a \`read\` key's floor,
 * so nothing but a policy naming them stops an oversight tier paging a run's full transcript,
 * and a hand-typed copy of this list is a deny rule that silently stops covering the surface the
 * day an operation joins it. DERIVED from the table for the same reason \`DECISION_BINDINGS\` is
 * derived from the answerer table one layer up.
 *
 * It is not a recommendation to deny them. A debugging agent is exactly who should hold these;
 * what the list buys is that granting them is a decision somebody made, rather than a default
 * that arrived with an upgrade.
 */
export const TELEMETRY_BINDINGS: readonly string[] = GATEKEEPER_BINDINGS.filter(
  (binding) => binding.telemetrySink !== undefined,
).map((binding) => binding.name)
`
}

/**
 * The argument bag one binding's session method takes, as TypeScript source.
 *
 * It is the `invoke` convention rendered as a type, so the two cannot describe different calls:
 * path parameters and query keys at the top level, the body under `body`. Requiredness is carried
 * through verbatim, because the whole reason a session is TYPED rather than an untyped bag is that
 * the caller learns what the deployment insists on before making the call rather than from its 400.
 */
function argumentType(operation) {
  const fields = [
    ...operation.pathParams.map((param) => `${param.wireName}: string`),
    ...operation.queryParams.map(
      (param) => `${param.wireName}${param.required ? '' : '?'}: string | number | boolean`,
    ),
    operation.body ? `body${operation.bodyOptional ? '?' : ''}: unknown` : null,
  ].filter(Boolean)
  if (fields.length === 0) return null
  const required =
    operation.pathParams.length > 0 ||
    operation.queryParams.some((param) => param.required) ||
    (operation.body && !operation.bodyOptional)
  return { text: `{ ${fields.join('; ')} }`, required: Boolean(required) }
}

/**
 * One granted operation as a method declaration for the rendered session `.d.ts`.
 *
 * The JSDoc carries the three facts an agent composing a call cannot see from the signature and
 * would otherwise guess at: what the operation does, which route it is (so a deployment's own logs
 * and this call can be correlated), and the scope floor it sits behind.
 */
function emitSessionSignature(operation) {
  const name = bindingName(operation)
  const argument = argumentType(operation)
  const parameters =
    argument === null ? '' : `args${argument.required ? '' : '?'}: ${argument.text}`
  const notes = [
    `\`${operation.httpMethod} ${operation.path}\`, scope floor \`${operation.minScope}\`.`,
  ]
  if (resultKind(operation) !== 'value') {
    notes.push(
      `Result is ${resultKind(operation)}, which a session call cannot carry: this operation is ` +
        'withheld from every tier.',
    )
  }
  const doc =
    `  /**\n   * ${operation.summary}\n   *\n` +
    notes.map((note) => `   * ${note}\n`).join('') +
    `   */\n`
  return {
    name,
    doc,
    signature: `  ${name}(${parameters}): Promise<unknown>\n`,
  }
}

/**
 * The per-operation method declarations a session's `.d.ts` is composed from.
 *
 * Generated rather than rendered whole because the declaration a caller should read is the one for
 * the tier they hold: a session carries exactly its granted operations, so a `.d.ts` naming the
 * full surface would promise methods the object does not have, which is the same lie the
 * hand-curated allow-list this table replaced used to tell. What ships is the SIGNATURES; the
 * composition is `renderSessionTypes`, a pure function over the names a policy actually granted.
 */
function emitSessionTypes(ir, placed) {
  const ordered = GROUPS.flatMap((group) => groupOperations(placed, group))
  const signatures = ordered.map((operation) => emitSessionSignature(operation))

  return `${BANNER}
// The session type declarations, surface version ${ir.info.version}: one method signature per
// \`/api/v1\` operation, ready to compose into the \`.d.ts\` an object-capability session serves
// through its \`getTypeScriptTypes()\`.
//
// WHAT IS DELIBERATELY ABSENT is the result shape. A session relays the deployment's own decoded
// JSON, and the authority for those shapes is the OpenAPI document this file is generated from,
// which every deployment serves at \`GET /api/v1/openapi.json\`. Inlining the model tree here
// would put a second copy of it inside every Worker bundle, free to disagree with the first the
// moment a consumer upgrades one and not the other. So results are \`unknown\` and SAY they are,
// rather than a hand-maintained subset that reads as complete.

/** One operation's session method, as the source lines a rendered \`.d.ts\` splices in. */
export interface SessionMethodSignature {
  /** The binding name, which is also the method's own spelling. */
  name: string
  /** The JSDoc block, indented and newline-terminated. */
  doc: string
  /** The method signature, indented and newline-terminated. */
  signature: string
}

/** Every \`/api/v1\` operation's session method signature, in resource-group order. */
export const SESSION_METHOD_SIGNATURES: readonly SessionMethodSignature[] = [
${signatures
  .map(
    (entry) =>
      `  {\n    name: ${lit(entry.name)},\n    doc: ${lit(entry.doc)},\n` +
      `    signature: ${lit(entry.signature)},\n  },\n`,
  )
  .join('')}]
`
}

/** Every generated file for the gatekeeper bindings, keyed by path within `sdk/gatekeeper/`. */
export function emit(ir, placed) {
  return {
    'src/bindings.generated.ts': emitBindings(ir, placed),
    'src/session-types.generated.ts': emitSessionTypes(ir, placed),
  }
}
