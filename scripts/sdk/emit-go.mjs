// Go emitter: `sdk/go/models_gen.go` + `operations_gen.go`.
//
// Go-specific choices worth stating:
//
//   - **Nullable and optional are both pointers**, and that is not laziness: Go's zero values are
//     indistinguishable from "the server sent 0 / false / empty string", so a non-pointer field
//     would make `progress: 0` and `progress: absent` the same value. Fields that are REQUIRED
//     and NOT nullable are plain values, because for those the distinction cannot arise.
//   - **`omitempty` only on genuinely optional fields.** Putting it on a required-but-nullable
//     field would drop an explicit `null` from a request body, which the server reads as "leave
//     this alone" rather than "clear it".
//   - **Enums are named string types with a constant per value**, never Go `iota` ints: the wire
//     form is the string, and an unknown value must round-trip rather than fail to decode.
//   - **Every method takes a `context.Context` first**, per the standard library convention, and
//     the transport honours its cancellation — a Go caller expects `ctx` to be the way out of a
//     stuck call, not an SDK-specific option struct.

import { pascal } from './ir.mjs'
import { GROUP_DOCS, GROUPS, groupOperations } from './surface.mjs'

const BANNER = `// GENERATED by \`pnpm gen:sdk\` from docs/openapi.json — DO NOT EDIT BY HAND.
// Regenerate after any change to the \`/api/v1\` contracts; \`pnpm check:sdk\` fails CI on drift.
`

/**
 * Initialisms Go style capitalises wholly (`Id` → `ID`). Applied to each word of an identifier,
 * so `taskId` → `TaskID` and `pipelineId` → `PipelineID` read as a Go author would write them.
 */
const INITIALISMS = new Set([
  'Id',
  'Url',
  'Api',
  'Http',
  'Json',
  'Sse',
  'Llm',
  'Ci',
  'Pr',
  'Vcs',
  'Ttl',
  'Uri',
  'Ms',
])

/** Go exported identifier for a wire name. */
function goName(wireName) {
  return pascal(wireName).replace(/([A-Z][a-z]+|[A-Z]+(?![a-z]))/g, (word) =>
    INITIALISMS.has(word) ? word.toUpperCase() : word,
  )
}

/** Go unexported identifier (a parameter name), kept off Go's keywords. */
const GO_KEYWORDS = new Set([
  'break',
  'case',
  'chan',
  'const',
  'continue',
  'default',
  'defer',
  'else',
  'fallthrough',
  'for',
  'func',
  'go',
  'goto',
  'if',
  'import',
  'interface',
  'map',
  'package',
  'range',
  'return',
  'select',
  'struct',
  'switch',
  'type',
  'var',
  'len',
  'cap',
  'new',
  'make',
  'ctx',
  'err',
])
function goParam(wireName) {
  const lowered = unexport(goName(wireName))
  return GO_KEYWORDS.has(lowered) ? `${lowered}Param` : lowered
}

/**
 * Unexport a Go identifier, lowercasing a LEADING INITIALISM whole rather than only its first
 * letter.
 *
 * `goName('id')` is `ID` — correct, and the reason a naive `charAt(0).toLowerCase()` produced
 * `iD`, which is what ten published Go method signatures said (`Cancel(ctx, iD string)`). It
 * compiles and it reads as a typo in godoc, which is a published surface.
 *
 * The rule is gofmt/golint's: the leading run of capitals is one word, so lowercase all of it —
 * unless a lowercase word follows, in which case the run's LAST capital starts that word and stays
 * (`APIKey` -> `apiKey`, not `apikey`). A run of one is the ordinary case (`TaskID` -> `taskID`).
 */
function unexport(exported) {
  const run = /^[A-Z]+/.exec(exported)?.[0].length ?? 0
  if (run === 0) return exported
  // `ID` -> `id`; `TaskID` -> `taskID`; `APIKey` -> `apiKey`.
  const lowercase = run === 1 || run === exported.length ? run : run - 1
  return exported.slice(0, lowercase).toLowerCase() + exported.slice(lowercase)
}

/** A Go string literal. */
function lit(value) {
  return JSON.stringify(String(value))
}

/** Doc comment lines prefixed with the declaration's own name, as Go convention wants. */
function doc(name, lines, indent = '') {
  const body = lines
    .filter((l) => l !== undefined && l !== null && l !== '')
    .flatMap((l) => wrap(String(l), 95 - indent.length))
  if (body.length === 0) return ''
  const first = name
    ? `${indent}// ${name} ${body[0].charAt(0).toLowerCase()}${body[0].slice(1)}`
    : `${indent}// ${body[0]}`
  return `${first}\n${body
    .slice(1)
    .map((l) => (l ? `${indent}// ${l}` : `${indent}//`))
    .join('\n')}\n`.replace(/\n+$/, '\n')
}

function wrap(text, width) {
  return text.split('\n').flatMap((paragraph) => {
    if (paragraph.length <= width) return [paragraph]
    const out = []
    let line = ''
    for (const word of paragraph.split(/\s+/)) {
      if (line && `${line} ${word}`.length > width) {
        out.push(line)
        line = word
      } else {
        line = line ? `${line} ${word}` : word
      }
    }
    if (line) out.push(line)
    return out
  })
}

/** The Go type for an IR reference. `pointer` forces a pointer even for a scalar. */
function goType(ref, pointer = false) {
  const base = (() => {
    switch (ref.kind) {
      case 'string':
        return 'string'
      case 'number':
        return 'float64'
      case 'integer':
        return 'int'
      case 'boolean':
        return 'bool'
      case 'const':
        return typeof ref.value === 'string' ? 'string' : 'any'
      case 'ref':
        return ref.name
      case 'array':
        // A slice is already nil-able, so an optional slice needs no extra pointer.
        return `[]${goType(ref.items)}`
      case 'map':
        return `map[string]${goType(ref.values)}`
      default:
        return 'any'
    }
  })()
  if (!pointer) return base
  if (base.startsWith('[]') || base.startsWith('map[') || base === 'any') return base
  return `*${base}`
}

function emitEnum(type) {
  // A `const` block is column-aligned by gofmt exactly like a struct body, so the names pad to
  // the widest one (see `alignFields` for why the emitter does this rather than shelling out).
  const width = Math.max(...type.values.map((value) => `${type.name}${goName(value)}`.length))
  const constants = type.values
    .map(
      (value) => `\t${`${type.name}${goName(value)}`.padEnd(width)} ${type.name} = ${lit(value)}`,
    )
    .join('\n')
  return (
    doc(type.name, [
      `is the \`${type.name}\` vocabulary as carried on the wire.`,
      '',
      'A string type rather than an int enum: the wire form IS the string, and an unknown ' +
        'value must round-trip rather than fail to decode — this surface is additive, so a ' +
        'client that refused a value the server legitimately added would break on a release it ' +
        'was never told about.',
    ]) +
    `type ${type.name} string\n\n` +
    `const (\n${constants}\n)\n\n` +
    doc(`${type.name}Values`, [`lists every ${type.name} this SDK release knows.`]) +
    `var ${type.name}Values = []${type.name}{${type.values.map((v) => `${type.name}${goName(v)}`).join(', ')}}\n`
  )
}

/** Struct-tag options for a field. */
function jsonTag(field) {
  // `omitempty` ONLY where absence is meaningful. On a required-but-nullable field it would
  // silently drop an explicit null from a request body, which the server reads as "leave this
  // alone" rather than "clear it".
  return `\`json:"${field.wireName}${field.required ? '' : ',omitempty'}"\``
}

function fieldDoc(field) {
  const notes = [field.doc]
  if (field.required && field.nullable) {
    notes.push('Always present; nil when the server has no value for it.')
  } else if (!field.required) {
    notes.push('May be absent entirely.')
  }
  return notes.filter(Boolean)
}

/**
 * Column-align a struct's field lines the way `gofmt` does.
 *
 * Emitted Go has to be gofmt-clean — a Go reader treats unformatted source as broken, and a
 * `gofmt -l` check in CI would flag every regeneration. Doing the alignment HERE rather than
 * shelling out to `gofmt` keeps generation deterministic and toolchain-free: a contributor
 * without a Go toolchain still produces byte-identical output, which is what makes the drift
 * guard meaningful.
 *
 * gofmt's tabwriter treats a COMMENT line as a run terminator: fields on either side of one are
 * aligned independently, so a documented field starts a fresh column block rather than padding to
 * match a distant neighbour. Reproducing that exactly is what makes the output a fixed point of
 * `gofmt`, so regenerating never fights a formatter.
 */
function alignFields(cells) {
  const lines = Array.from({ length: cells.length })
  let run = []

  const flush = () => {
    if (run.length === 0) return
    const nameWidth = Math.max(...run.map(({ cell }) => cell[0].length))
    const typeWidth = Math.max(...run.map(({ cell }) => cell[1].length))
    for (const { index, cell } of run) {
      lines[index] = `\t${cell[0].padEnd(nameWidth)} ${cell[1].padEnd(typeWidth)} ${cell[2]}`
    }
    run = []
  }

  cells.forEach((cell, index) => {
    // `cell[3]` is truthy when this field is preceded by a doc comment, which ends the run above.
    if (cell[3]) flush()
    run.push({ index, cell })
  })
  flush()
  // A run of one needs no padding at all — gofmt emits single columns unpadded.
  return lines.map((line) => line.replace(/\s+$/, ''))
}

function emitObject(type) {
  // Pointer whenever the value can be genuinely absent OR genuinely null — Go's zero values
  // cannot express either on their own.
  const cells = type.fields.map((field) => [
    goName(field.wireName),
    goType(field.type, !field.required || field.nullable),
    jsonTag(field),
    fieldDoc(field).length > 0,
  ])
  const aligned = alignFields(cells)
  const fields = type.fields
    .map((field, index) => doc(goName(field.wireName), fieldDoc(field), '\t') + aligned[index])
    .join('\n')
  return (
    doc(type.name, [`is the \`${type.name}\` wire model.`]) +
    `type ${type.name} struct {\n${fields}\n}\n`
  )
}

/**
 * A tagged union. Go has no sum type, so the union is a struct holding one populated pointer per
 * variant plus the discriminator — which keeps it a plain value a caller can switch on, and
 * keeps `encoding/json` able to decode it without a custom scheme the caller has to know about.
 */
function emitUnion(type) {
  const variants = type.variants.filter((v) => v.kind === 'ref')
  if (variants.length === 0 || !type.discriminator) {
    return (
      doc(type.name, [`is an untagged \`${type.name}\`; decode it yourself.`]) +
      `type ${type.name} = json.RawMessage\n`
    )
  }
  const fields = variants
    .map(
      (variant, index) =>
        `\t// ${variant.name} is set when ${type.discriminator.property} == ${lit(type.discriminator.values[index])}.\n` +
        `\t${variant.name} *${variant.name}`,
    )
    .join('\n')
  const cases = variants
    .map(
      (variant, index) =>
        `\tcase ${lit(type.discriminator.values[index])}:\n` +
        `\t\tvar out ${variant.name}\n` +
        '\t\tif err := json.Unmarshal(data, &out); err != nil {\n' +
        '\t\t\treturn err\n' +
        '\t\t}\n' +
        `\t\tu.${variant.name} = &out\n` +
        '\t\treturn nil',
    )
    .join('\n')
  return (
    doc(type.name, [
      `is a \`${type.name}\`: exactly one variant pointer is non-nil, chosen by ${type.discriminator.property}.`,
      '',
      'Go has no sum type, so the variants are pointers on one struct. Switch on Kind (or ' +
        'test the pointers) to reach the populated one.',
    ]) +
    `type ${type.name} struct {\n` +
    `\t// Kind is the discriminator the server sent, INCLUDING one this SDK release does not\n` +
    `\t// know — in which case every variant pointer is nil and Raw holds the body verbatim.\n` +
    '\tKind string\n' +
    `${fields}\n` +
    '\t// Raw is the undecoded body, always populated.\n' +
    '\tRaw json.RawMessage\n' +
    '}\n\n' +
    doc('UnmarshalJSON', [`decodes a ${type.name} by its ${type.discriminator.property} tag.`]) +
    `func (u *${type.name}) UnmarshalJSON(data []byte) error {\n` +
    '\tu.Raw = append(json.RawMessage(nil), data...)\n' +
    '\tvar tag struct {\n' +
    `\t\tKind string \`json:"${type.discriminator.property}"\`\n` +
    '\t}\n' +
    '\tif err := json.Unmarshal(data, &tag); err != nil {\n' +
    '\t\treturn err\n' +
    '\t}\n' +
    '\tu.Kind = tag.Kind\n' +
    '\tswitch tag.Kind {\n' +
    `${cases}\n` +
    '\t}\n' +
    '\t// An unknown variant is NOT an error: the surface is additive, and Raw + Kind still let\n' +
    '\t// a caller see exactly what arrived.\n' +
    '\treturn nil\n' +
    '}\n\n' +
    doc('MarshalJSON', [`re-emits the variant that is set, or the raw body when none is.`]) +
    `func (u ${type.name}) MarshalJSON() ([]byte, error) {\n` +
    variants
      .map((v) => `\tif u.${v.name} != nil {\n\t\treturn json.Marshal(u.${v.name})\n\t}\n`)
      .join('') +
    '\tif len(u.Raw) > 0 {\n\t\treturn u.Raw, nil\n\t}\n' +
    '\treturn []byte("null"), nil\n' +
    '}\n'
  )
}

function emitModels(ir) {
  const blocks = ir.types.map((type) => {
    if (type.kind === 'enum') return emitEnum(type)
    if (type.kind === 'union') return emitUnion(type)
    return emitObject(type)
  })
  return `${BANNER}
// Wire models for the cat-factory public API (/api/v1), surface version ${ir.info.version}.
//
// A pointer field is one that can be genuinely ABSENT or genuinely NULL — Go's zero values
// cannot express either, so \`Progress: 0\` and "no progress reported" would otherwise be the
// same value. A plain (non-pointer) field is one the contract guarantees is always sent.

package catfactory

import "encoding/json"

${blocks.join('\n')}`
}

/** The generated query struct name for an operation, or null when it takes none. */
function queryTypeName(operation) {
  return operation.queryParams.length > 0
    ? `${pascal(operation.group)}${pascal(operation.method)}Query`
    : null
}

function emitQueryTypes(placed) {
  return placed
    .filter((operation) => operation.queryParams.length > 0)
    .map((operation) => {
      const name = queryTypeName(operation)
      const fields = operation.queryParams
        .map(
          (param) =>
            doc(
              goName(param.wireName),
              [
                param.doc,
                // Required parameters are still POINTERS: the struct is one shape for every
                // operation and a value field would send a zero rather than nothing. What the
                // doc must not do is imply that leaving it nil is a call the deployment serves.
                param.required
                  ? 'Is REQUIRED: the deployment refuses a nil here with a 400 naming it.'
                  : 'Zero value means "not sent".',
              ],
              '\t',
            ) + `\t${goName(param.wireName)} ${goType(param.type, true)}`,
        )
        .join('\n')
      const encode = operation.queryParams
        .map(
          (param) =>
            `\tif q.${goName(param.wireName)} != nil {\n` +
            `\t\tout[${lit(param.wireName)}] = fmt.Sprintf("%v", *q.${goName(param.wireName)})\n` +
            '\t}',
        )
        .join('\n')
      return (
        doc(name, [
          `holds the query parameters for ${pascal(operation.group)}Service.${pascal(operation.method)}.`,
        ]) +
        `type ${name} struct {\n${fields}\n}\n\n` +
        `func (q *${name}) values() map[string]string {\n` +
        '\tout := map[string]string{}\n' +
        '\tif q == nil {\n\t\treturn out\n\t}\n' +
        `${encode}\n` +
        '\treturn out\n' +
        '}\n'
      )
    })
    .join('\n')
}

/** The Go expression building the request path. */
function pathExpression(operation) {
  if (operation.pathParams.length === 0) return lit(operation.path)
  const format = operation.path.replace(/\{(\w+)\}/g, '%s')
  const args = operation.pathParams.map((p) => `pathEscape(${goParam(p.wireName)})`)
  return `fmt.Sprintf(${lit(format)}, ${args.join(', ')})`
}

function emitMethod(operation) {
  const name = pascal(operation.method)
  const service = `${pascal(operation.group)}Service`
  const query = queryTypeName(operation)
  const params = [
    'ctx context.Context',
    ...operation.pathParams.map((p) => `${goParam(p.wireName)} string`),
    operation.body ? `body ${goType(operation.body)}` : null,
    query ? `query *${query}` : null,
  ].filter(Boolean)

  const returns = operation.stream
    ? '(*EventStream, error)'
    : operation.binary
      ? '([]byte, error)'
      : operation.result
        ? `(*${goType(operation.result)}, error)`
        : 'error'

  const requestLiteral =
    '\treq := requestSpec{\n' +
    `\t\tMethod: ${lit(operation.httpMethod)},\n` +
    `\t\tPath:   ${pathExpression(operation)},\n` +
    (operation.body ? '\t\tBody:   body,\n' : '') +
    (query ? '\t\tQuery:  query.values(),\n' : '') +
    '\t}\n'

  const call = operation.stream
    ? '\treturn s.client.stream(ctx, req)\n'
    : operation.binary
      ? '\treturn s.client.requestBytes(ctx, req)\n'
      : operation.result
        ? `\tvar out ${goType(operation.result)}\n` +
          '\tif err := s.client.request(ctx, req, &out); err != nil {\n\t\treturn nil, err\n\t}\n' +
          '\treturn &out, nil\n'
        : '\treturn s.client.requestNoContent(ctx, req)\n'

  return (
    doc(name, [
      operation.summary,
      '',
      operation.description,
      '',
      `${operation.httpMethod} ${operation.path} (operation ${operation.id}).`,
    ]) +
    `func (s *${service}) ${name}(${params.join(', ')}) ${returns} {\n` +
    requestLiteral +
    call +
    '}\n'
  )
}

/**
 * An auto-paging iterator over a keyset-paginated list. Go 1.23 range-over-func, so a caller
 * writes `for item, err := range svc.ListRunsAll(ctx, nil) { … }` — the idiomatic shape, and the
 * only one that can surface a mid-iteration error without panicking or silently truncating.
 */
function emitPager(operation) {
  const name = `${pascal(operation.method)}All`
  const service = `${pascal(operation.group)}Service`
  const query = queryTypeName(operation)
  const itemField = goName(operation.paginates)
  const listType = goType(operation.result)
  const params = [
    'ctx context.Context',
    ...operation.pathParams.map((p) => `${goParam(p.wireName)} string`),
    query ? `query *${query}` : null,
  ].filter(Boolean)
  const callArgs = [
    'ctx',
    ...operation.pathParams.map((p) => goParam(p.wireName)),
    query ? '&page' : null,
  ].filter(Boolean)

  return (
    doc(name, [
      `iterates every ${operation.paginates} across every page of ${pascal(operation.method)}.`,
      '',
      'Follows nextCursor until the server reports no further page. Yields (item, nil) per ' +
        'item and, on a failure mid-iteration, one final (zero, err) — so a partial walk is ' +
        'never mistaken for a complete one.',
    ]) +
    `func (s *${service}) ${name}(${params.join(', ')}) iter.Seq2[${listType}Item, error] {\n` +
    `\treturn func(yield func(${listType}Item, error) bool) {\n` +
    (query
      ? '\t\tvar page ' + query + '\n' + '\t\tif query != nil {\n\t\t\tpage = *query\n\t\t}\n'
      : '') +
    '\t\tfor {\n' +
    `\t\t\tresult, err := s.${pascal(operation.method)}(${callArgs.join(', ')})\n` +
    '\t\t\tif err != nil {\n' +
    `\t\t\t\tvar zero ${listType}Item\n` +
    '\t\t\t\tyield(zero, err)\n' +
    '\t\t\t\treturn\n' +
    '\t\t\t}\n' +
    `\t\t\tfor _, item := range result.${itemField} {\n` +
    '\t\t\t\tif !yield(item, nil) {\n\t\t\t\t\treturn\n\t\t\t\t}\n' +
    '\t\t\t}\n' +
    '\t\t\tif result.NextCursor == nil || *result.NextCursor == "" {\n\t\t\t\treturn\n\t\t\t}\n' +
    (query
      ? '\t\t\tif page.Cursor != nil && *page.Cursor == *result.NextCursor {\n' +
        `\t\t\t\tvar zero ${listType}Item\n` +
        '\t\t\t\tyield(zero, ErrRepeatedCursor)\n' +
        '\t\t\t\treturn\n' +
        '\t\t\t}\n' +
        '\t\t\tpage.Cursor = result.NextCursor\n'
      : '') +
    '\t\t}\n' +
    '\t}\n' +
    '}\n'
  )
}

/** `type XItem = <the element type of X's paginated field>`, so a pager needs no second name. */
function emitPagerItemAlias(ir, operation) {
  const listType = goType(operation.result)
  const definition = ir.types.find((t) => t.name === listType)
  const listField = definition?.fields.find((f) => f.wireName === operation.paginates)
  const element = listField?.type.kind === 'array' ? goType(listField.type.items) : 'any'
  return (
    doc(`${listType}Item`, [
      `is the element type of ${listType}.${goName(operation.paginates)}.`,
      '',
      'An alias rather than a second declaration, so the pager cannot drift from the list it ' +
        'pages over.',
    ]) + `type ${listType}Item = ${element}\n`
  )
}

function emitService(placed, group) {
  const operations = groupOperations(placed, group)
  const name = `${pascal(group)}Service`
  return (
    doc(name, [GROUP_DOCS[group]]) +
    `type ${name} struct {\n\tclient *Client\n}\n\n` +
    operations
      .flatMap((operation) => [
        emitMethod(operation),
        operation.paginates ? emitPager(operation) : null,
      ])
      .filter(Boolean)
      .join('\n')
  )
}

function emitOperations(ir, placed) {
  const aliases = placed
    .filter((operation) => operation.paginates)
    .map((operation) => emitPagerItemAlias(ir, operation))
  return `${BANNER}
// The resource services: one type per resource group, each a thin shell over the hand-written
// transport in client.go. Nothing here decides retry, auth, error mapping or stream framing.

package catfactory

import (
	"context"
	"fmt"
	"iter"
)

${emitQueryTypes(placed)}
${aliases.join('\n')}
${GROUPS.map((group) => emitService(placed, group)).join('\n')}`
}

/** Every generated file for the Go SDK, keyed by path within `sdk/go/`. */
export function emit(ir, placed) {
  return {
    'models_gen.go': emitModels(ir),
    'operations_gen.go': emitOperations(ir, placed),
  }
}
