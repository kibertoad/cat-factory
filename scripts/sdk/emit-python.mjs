// Python emitter: `sdk/python/cat_factory/models.py` + `operations.py`.
//
// Idiomatic-Python choices worth stating, because each is a place a mechanical translation of
// the spec would produce something a Python user would not write:
//
//   - **Models are frozen dataclasses with an explicit `from_dict`**, not `TypedDict` and not a
//     Pydantic dependency. A dataclass gives attribute access, `repr` and equality for free and
//     costs the SDK no third-party runtime — a client library that drags Pydantic into every
//     consumer's dependency tree is a real cost, and this surface needs no validation engine.
//   - **Unknown fields are RETAINED, never dropped.** `/api/v1` is additive forever, so a
//     response routinely carries fields an older SDK has no attribute for. They land on `extra`
//     so a caller on an older SDK can still reach a new field instead of upgrading first.
//   - **Enums are `str`-subclassing** so `task.status == 'done'` works, and decoding an
//     UNKNOWN value yields the raw string rather than raising. A client that hard-fails on a
//     value the server legitimately added would turn every additive server release into an
//     outage for everyone who had not upgraded.
//   - **Optional vs nullable both surface as `| None`** — Python has no third state — but the
//     distinction is kept in the docstring, and a field that is merely ABSENT stays absent from
//     the request body rather than being sent as an explicit `null` (which the server would
//     read as "clear this", not "leave it alone").

import { pascal, snake } from './ir.mjs'
import { GROUP_DOCS, GROUPS, groupOperations } from './surface.mjs'

const BANNER = `# GENERATED by \`pnpm gen:sdk\` from docs/openapi.json — DO NOT EDIT BY HAND.
# Regenerate after any change to the \`/api/v1\` contracts; \`pnpm check:sdk\` fails CI on drift.
`

/** Python keywords and soft-keywords a field or parameter name must not collide with. */
const RESERVED = new Set([
  'and',
  'as',
  'assert',
  'async',
  'await',
  'break',
  'class',
  'continue',
  'def',
  'del',
  'elif',
  'else',
  'except',
  'finally',
  'for',
  'from',
  'global',
  'if',
  'import',
  'in',
  'is',
  'lambda',
  'None',
  'nonlocal',
  'not',
  'or',
  'pass',
  'raise',
  'return',
  'True',
  'False',
  'try',
  'while',
  'with',
  'yield',
  'match',
  'case',
  'type',
  'self',
])

/** The Python attribute name for a wire field, suffixed away from a keyword collision. */
function attr(wireName) {
  const name = snake(wireName)
  return RESERVED.has(name) ? `${name}_` : name
}

/** A Python string literal. */
function lit(value) {
  return `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

/** Wrap a docstring body, or return '' when there is nothing to say. */
function docstring(lines, indent) {
  const body = lines
    .filter((l) => l !== undefined && l !== null && l !== '')
    .flatMap((l) => wrap(String(l), 92 - indent.length))
  if (body.length === 0) return ''
  if (body.length === 1 && body[0].length < 88 - indent.length) return `${indent}"""${body[0]}"""\n`
  return `${indent}"""${body[0]}\n${body
    .slice(1)
    .map((l) => (l ? `${indent}${l}` : ''))
    .join('\n')}\n${indent}"""\n`
}

/** Greedy word wrap, so generated docstrings stay inside a normal line budget. */
function wrap(text, width) {
  return text.split('\n').flatMap((paragraph) => {
    if (paragraph.length <= width) return [paragraph]
    const out = []
    let line = ''
    for (const word of paragraph.split(/\s+/)) {
      if (line && `${line} ${word}`.length > width) {
        out.push(line)
        line = word
      } else {
        line = line ? `${line} ${word}` : word
      }
    }
    if (line) out.push(line)
    return out
  })
}

/** The Python type annotation for an IR type reference. */
function pyType(ref) {
  const base = (() => {
    switch (ref.kind) {
      case 'string':
        return 'str'
      case 'number':
        return 'float'
      case 'integer':
        return 'int'
      case 'boolean':
        return 'bool'
      case 'const':
        return typeof ref.value === 'string' ? 'str' : 'Any'
      case 'ref':
        // A BARE name, not a quoted forward reference: `from __future__ import annotations`
        // makes every annotation lazy, so nothing here is evaluated at class-definition time,
        // and a bare name is what a type checker and a reader both want to see.
        return ref.name
      case 'array':
        return `list[${pyType(ref.items)}]`
      case 'map':
        return `dict[str, ${pyType(ref.values)}]`
      default:
        return 'Any'
    }
  })()
  return ref.nullable ? `${base} | None` : base
}

/**
 * Names of the IR types that are ENUMS, populated per emit. An enum ref decodes leniently
 * (`_enum(Cls, value)`) rather than through `from_dict`, which only a dataclass has — and the
 * emitter cannot tell the two apart from a `{kind: 'ref'}` alone.
 */
let ENUM_NAMES = new Set()

/**
 * The expression that decodes a wire value into `ref`'s Python type.
 *
 * `value` is an expression naming the raw JSON. Scalars pass through — the SDK deliberately does
 * NOT coerce or validate them, because a client that rejects what the server sent is worse than
 * one that hands it on: the caller can see a wrong value, but cannot see a call that raised
 * before returning.
 */
function decodeExpr(ref, value) {
  switch (ref.kind) {
    case 'ref':
      return ENUM_NAMES.has(ref.name)
        ? `_enum(${ref.name}, ${value})`
        : `${ref.name}.from_dict(${value})`
    case 'array':
      return `[${decodeExpr(ref.items, 'item')} for item in ${value} or []]`
    case 'map':
      return `{key: ${decodeExpr(ref.values, 'val')} for key, val in (${value} or {}).items()}`
    default:
      return value
  }
}

/** True when decoding `ref` needs more than a pass-through. */
function needsDecode(ref) {
  return ref.kind === 'ref' || ref.kind === 'array' || ref.kind === 'map'
}

/** Record which IR type names are enums, so `decodeExpr` can branch on it. */
function noteEnums(ir) {
  ENUM_NAMES = new Set(ir.types.filter((type) => type.kind === 'enum').map((type) => type.name))
}

/** The expression that encodes a Python value back to JSON. */
function encodeExpr(ref, value) {
  switch (ref.kind) {
    case 'ref':
      return `_encode(${value})`
    case 'array':
      return `[_encode(item) for item in ${value}]`
    case 'map':
      return `{key: _encode(val) for key, val in ${value}.items()}`
    default:
      return value
  }
}

function emitEnum(type) {
  const members = type.values.map((value) => `    ${enumMember(value)} = ${lit(value)}`).join('\n')
  return (
    `class ${type.name}(StrEnum):\n` +
    docstring(
      [
        `The \`${type.name}\` vocabulary.`,
        '',
        'A `StrEnum`, so a member IS its wire string: it compares equal to it, formats as it ' +
          'in an f-string, and serialises as it. A plain `(str, Enum)` would satisfy the first ' +
          'of those and silently fail the other two — `str(TaskStatus.PLANNED)` is ' +
          '"TaskStatus.PLANNED", which is the value that ends up in a log line or a report.',
        '',
        'An UNKNOWN value decodes to the plain string rather than raising: this surface is ' +
          'additive, and a client that refused a value the server legitimately added would ' +
          'break on a release it was never told about.',
      ],
      '    ',
    ) +
    `${members}\n`
  )
}

/** A valid Python identifier for an enum value (`pr_ready` → `PR_READY`, `2xx` → `VALUE_2XX`). */
function enumMember(value) {
  const name = snake(value).toUpperCase()
  return /^[A-Z]/.test(name) ? name : `VALUE_${name}`
}

/** Fields ordered so every required one precedes every defaulted one (a dataclass rule). */
function orderedFields(type) {
  return [...type.fields].sort((a, b) => {
    const aRequired = a.required && !a.nullable
    const bRequired = b.required && !b.nullable
    if (aRequired !== bRequired) return aRequired ? -1 : 1
    return 0
  })
}

function fieldDoc(field) {
  const notes = [field.doc]
  if (field.required && field.nullable) {
    notes.push('Always present; ``None`` when the server has no value for it.')
  } else if (!field.required) {
    notes.push('May be absent entirely.')
  }
  return notes.filter(Boolean).join(' ')
}

function emitObject(type) {
  const fields = orderedFields(type)
  const declarations = fields
    .map((field) => {
      const annotation =
        field.required && !field.nullable
          ? pyType(field.type)
          : `${pyType(field.type)}${field.type.nullable ? '' : ' | None'}`
      const dflt = field.required && !field.nullable ? '' : ' = None'
      const comment = fieldDoc(field)
      return `${comment ? `    #: ${wrap(comment, 88).join('\n    #: ')}\n` : ''}    ${attr(field.wireName)}: ${annotation}${dflt}`
    })
    .join('\n')

  const decodes = fields
    .map((field) => {
      const raw = `data.get(${lit(field.wireName)})`
      if (!needsDecode(field.type)) return `            ${attr(field.wireName)}=${raw},`
      const guard = field.nullable || !field.required ? `None if ${raw} is None else ` : ''
      return `            ${attr(field.wireName)}=${guard}${decodeExpr(field.type, raw)},`
    })
    .join('\n')

  const encodes = fields
    .map((field) => {
      const value = `self.${attr(field.wireName)}`
      const body = `out[${lit(field.wireName)}] = ${encodeExpr(field.type, value)}`
      // The gate is REQUIRED, not "required and non-null". A required-but-nullable field is
      // always part of the payload and its null is a real value the server acts on; omitting it
      // would say "leave this alone" where the caller meant "clear it". Only a field that may be
      // ABSENT is dropped when unset — which is the whole reason the IR keeps the two apart.
      if (field.required) return `        ${body}`
      return `        if ${value} is not None:\n            ${body}`
    })
    .join('\n')

  return (
    '@dataclass(frozen=True, slots=True)\n' +
    `class ${type.name}:\n` +
    docstring([`\`${type.name}\`, as carried on the wire.`], '    ') +
    '\n' +
    `${declarations}\n` +
    '\n' +
    '    #: Fields the server sent that this SDK release has no attribute for. `/api/v1` is\n' +
    '    #: additive, so these are RETAINED rather than dropped: a caller on an older SDK can\n' +
    '    #: still reach a newly added field instead of having to upgrade first.\n' +
    // `_dc_field`, never a bare `field`: a wire property may legitimately be NAMED `field`
    // (`PublicInputGateDecisionIssue.field` is), and a dataclass attribute of that name SHADOWS
    // the import inside the class body, so the next line would call the attribute's `None`
    // default instead of `dataclasses.field` and the module would fail to import. Not just this
    // model's: `__init__.py` reaches models through `client` and `operations`, so one
    // unimportable class takes out every import of the package. The underscore prefix also keeps
    // the alias out of the module's public surface.
    //
    // This is the ONE executable expression in a generated class BODY, which is what makes it the
    // one name a wire property can shadow: the decorator is evaluated at MODULE scope before the
    // body binds anything, and annotations are strings under `from __future__ import
    // annotations`. Regenerate-and-diff structurally cannot catch this class of bug (the emitter
    // is consistent in both halves), so the guard is `sdk/python/tests/test_models.py`, which
    // imports the real generated module and round-trips the shape that first broke it.
    '    extra: dict[str, Any] = _dc_field(default_factory=dict)\n' +
    '\n' +
    '    @classmethod\n' +
    `    def from_dict(cls, data: Mapping[str, Any]) -> "${type.name}":\n` +
    `        """Decode a \`${type.name}\` from its JSON object."""\n` +
    '        known = {' +
    fields.map((f) => lit(f.wireName)).join(', ') +
    '}\n' +
    '        return cls(\n' +
    `${decodes}\n` +
    '            extra={k: v for k, v in data.items() if k not in known},\n' +
    '        )\n' +
    '\n' +
    '    def to_dict(self) -> dict[str, Any]:\n' +
    '        """Encode back to the JSON object shape the API expects."""\n' +
    '        out: dict[str, Any] = dict(self.extra)\n' +
    `${encodes || '        pass'}\n` +
    '        return out\n'
  )
}

function emitUnion(type) {
  const members = type.variants.map((v) => (v.kind === 'ref' ? v.name : pyType(v)))
  const notes = [
    `\`${type.name}\` — one of: ${members.join(', ')}.`,
    type.discriminator
      ? `Discriminated by \`${type.discriminator.property}\`; decode with \`decode_${snake(type.name)}\`.`
      : '',
  ]
  const alias = `${type.name}: TypeAlias = ${members.join(' | ')}`
  if (!type.discriminator) return `#: ${notes.filter(Boolean).join(' ')}\n${alias}\n`
  const branches = type.discriminator.values
    .map(
      (value, index) =>
        `    if tag == ${lit(value)}:\n        return ${members[index]}.from_dict(data)`,
    )
    .join('\n')
  return (
    `#: ${notes.filter(Boolean).join(' ')}\n${alias}\n\n` +
    `def decode_${snake(type.name)}(data: Mapping[str, Any]) -> ${type.name}:\n` +
    docstring(
      [
        `Decode a \`${type.name}\` by its \`${type.discriminator.property}\` tag.`,
        '',
        'An unrecognised tag raises rather than guessing a variant: every variant here has a ' +
          'different shape, so picking the wrong one would hand back a value whose fields are ' +
          'silently absent instead of an error naming what was not understood.',
      ],
      '    ',
    ) +
    `    tag = data.get(${lit(type.discriminator.property)})\n` +
    `${branches}\n` +
    `    raise ValueError(f"Unknown ${type.name} ${type.discriminator.property}: {tag!r}")\n`
  )
}

function emitModels(ir) {
  noteEnums(ir)
  // Unions are emitted LAST. A union alias (`PublicDecision = A | B | C`) is a real runtime
  // expression over the variant classes, so every variant must already be defined — emitting in
  // the types' alphabetical order would evaluate `A | B` before `A` exists.
  const ordered = [
    ...ir.types.filter((type) => type.kind !== 'union'),
    ...ir.types.filter((type) => type.kind === 'union'),
  ]
  const blocks = ordered.map((type) => {
    if (type.kind === 'enum') return emitEnum(type)
    if (type.kind === 'union') return emitUnion(type)
    return emitObject(type)
  })
  return `${BANNER}
"""Wire models for the cat-factory public API (\`/api/v1\`), surface version ${ir.info.version}.

Every model is a frozen dataclass with \`from_dict\` / \`to_dict\`. Unknown fields are kept on
\`extra\` rather than dropped, and an unknown enum value decodes to its plain string, so an SDK
release older than the deployment it talks to degrades to "less typed", never to "raises".
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field as _dc_field
from enum import Enum, StrEnum
from typing import Any, TypeAlias


def _enum(cls: type[Enum], value: Any) -> Any:
    """Decode an enum value LENIENTLY.

    An unrecognised value comes back as the plain string rather than raising. The /api/v1
    surface is additive forever and a deployment will send values an older SDK has never heard
    of; a strict decode would turn every additive server release into an outage for anyone who
    had not upgraded. The members subclass str, so comparing against either form works.
    """
    if value is None:
        return None
    try:
        return cls(value)
    except ValueError:
        return value


def _encode(value: Any) -> Any:
    """Encode a model, enum, list or scalar back to its JSON form."""
    if hasattr(value, "to_dict"):
        return value.to_dict()
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, list):
        return [_encode(item) for item in value]
    if isinstance(value, dict):
        return {key: _encode(val) for key, val in value.items()}
    return value


${blocks.join('\n\n')}`
}

/** The Python method signature parameters for an operation. */
function methodParams(operation) {
  const params = ['self', ...operation.pathParams.map((p) => `${attr(p.wireName)}: str`)]
  if (operation.body) params.push(`body: ${pyType(operation.body)}`)
  if (operation.queryParams.length > 0) {
    // Query parameters are keyword-only: they are all optional and unordered, and a positional
    // call site would silently re-bind if the spec ever reorders them.
    params.push('*')
    for (const param of operation.queryParams) {
      params.push(`${attr(param.wireName)}: ${pyType(param.type)} | None = None`)
    }
  }
  params.push('timeout: float | None = None')
  return params
}

function emitMethod(operation) {
  const name = snake(operation.method)
  const pathExpr = operation.path.replace(/\{(\w+)\}/g, (_m, wire) => `{_quote(${attr(wire)})}`)
  const queryDict =
    operation.queryParams.length > 0
      ? `{${operation.queryParams.map((p) => `${lit(p.wireName)}: ${attr(p.wireName)}`).join(', ')}}`
      : 'None'
  const [returns, transportCall, prefix, tail] = operation.stream
    ? ['EventStream', 'stream', 'return ', '']
    : operation.result
      ? [
          pyType(operation.result),
          'request',
          'raw = ',
          `        return ${needsDecode(operation.result) ? decodeExpr(operation.result, 'raw') : 'raw'}\n`,
        ]
      : ['None', 'request_no_content', '', '']

  return (
    `    def ${name}(${methodParams(operation).join(', ')}) -> ${returns}:\n` +
    docstring(
      [
        operation.summary,
        '',
        operation.description,
        '',
        `\`${operation.httpMethod} ${operation.path}\` (operation \`${operation.id}\`).`,
      ],
      '        ',
    ) +
    `        ${prefix}self._transport.${transportCall}(\n` +
    `            ${lit(operation.httpMethod)},\n` +
    `            f"${pathExpr}",\n` +
    (operation.body ? '            body=_encode(body),\n' : '') +
    `            query=${queryDict},\n` +
    '            timeout=timeout,\n' +
    '        )\n' +
    tail
  )
}

/**
 * An auto-paging generator over a keyset-paginated list.
 *
 * The item type is read off the list model's own field, so it cannot drift from what the
 * endpoint actually returns.
 */
function emitPager(operation) {
  const name = snake(operation.method)
  const listType = operation.result.name
  const itemField = operation.result.kind === 'ref' ? operation.paginates : operation.paginates
  const params = methodParams(operation)
  const passthrough = [
    ...operation.pathParams.map((p) => attr(p.wireName)),
    ...operation.queryParams
      .filter((p) => p.wireName !== 'cursor')
      .map((p) => `${attr(p.wireName)}=${attr(p.wireName)}`),
    'cursor=page_cursor',
    'timeout=timeout',
  ]
  return (
    `    def ${name}_all(${params.join(', ')}) -> Iterator[Any]:\n` +
    docstring(
      [
        `Every \`${itemField}\` across every page of \`${name}()\`, as they arrive.`,
        '',
        'Follows `next_cursor` until the server reports no further page. A page may ' +
          'legitimately come back empty while `next_cursor` is still set, so this pages until ' +
          'the cursor is None rather than stopping at the first empty page.',
        '',
        `Yields items of \`${listType}.${attr(itemField)}\`.`,
      ],
      '        ',
    ) +
    // Seed the loop from the caller's own `cursor` (resuming mid-stream is legitimate) but
    // advance a LOCAL, so the caller's argument is never mutated under them.
    '        page_cursor = cursor\n' +
    '        while True:\n' +
    `            page = self.${name}(${passthrough.join(', ')})\n` +
    `            yield from page.${attr(itemField)}\n` +
    '            if not page.next_cursor:\n' +
    '                return\n' +
    '            if page.next_cursor == page_cursor:\n' +
    '                raise _repeated_cursor()\n' +
    '            page_cursor = page.next_cursor\n'
  )
}

function emitResource(placed, group) {
  const operations = groupOperations(placed, group)
  const methods = operations.flatMap((operation) => [
    emitMethod(operation),
    operation.paginates ? emitPager(operation) : null,
  ])
  return (
    `class ${pascal(group)}Resource:\n` +
    docstring([GROUP_DOCS[group]], '    ') +
    '\n' +
    '    def __init__(self, transport: Transport) -> None:\n' +
    '        self._transport = transport\n' +
    '\n' +
    methods.filter(Boolean).join('\n')
  )
}

function emitOperations(ir, placed) {
  noteEnums(ir)
  const modelNames = new Set(ir.types.map((t) => t.name))
  const resources = GROUPS.map((group) => emitResource(placed, group)).join('\n\n')
  const referenced = [...modelNames]
    .filter((name) => new RegExp(`\\b${name}\\b`).test(resources))
    .sort()
  return `${BANNER}
"""The resource clients: one class per resource group, each a thin shell over the hand-written
\`\`Transport\`\`. Nothing here decides retry, auth, error mapping or stream framing — that is
\`\`_http.py\`\` / \`\`errors.py\`\` / \`\`_sse.py\`\`, so those change without touching 38 methods.
"""

from __future__ import annotations

from collections.abc import Iterator
from typing import Any
from urllib.parse import quote

from ._http import Transport
from ._sse import EventStream
from .errors import _repeated_cursor
from .models import (
    _encode,
    _enum,
${referenced.map((n) => `    ${n},`).join('\n')}
)


def _quote(value: str) -> str:
    """Percent-encode a path parameter.

    An id is server-supplied but travels through a caller's own storage, and one carrying a
    slash would otherwise re-target the request at a different route rather than 404 on the id
    it names.
    """
    return quote(str(value), safe="")


${resources}

def build_resources(transport: Transport) -> dict[str, Any]:
    """Every resource client, keyed by the attribute it is mounted at on the client."""
    return {
${GROUPS.map((g) => `        ${lit(g)}: ${pascal(g)}Resource(transport),`).join('\n')}
    }
`
}

/** Every generated file for the Python SDK, keyed by path within `sdk/python/`. */
export function emit(ir, placed) {
  return {
    'cat_factory/models.py': emitModels(ir),
    'cat_factory/operations.py': emitOperations(ir, placed),
  }
}
