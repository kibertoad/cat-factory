// TypeScript emitter: `sdk/typescript/src/models.generated.ts` + `operations.generated.ts`.
//
// Only the DATA and the CALL SHAPE are generated. The transport, the error hierarchy, the SSE
// reader and the retry policy are hand-written under `sdk/typescript/src/` and are what the
// generated layer calls into — so a spec change never rewrites a line of behaviour, and a
// behaviour change never has to be re-applied across 42 operations.

import { camel, pascal } from './ir.mjs'
import { GROUP_DOCS, GROUPS, groupOperations } from './surface.mjs'

const BANNER = `// GENERATED by \`pnpm gen:sdk\` from docs/openapi.json — DO NOT EDIT BY HAND.
// Regenerate after any change to the \`/api/v1\` contracts; \`pnpm check:sdk\` fails CI on drift.
`

/** A single-quoted TS string literal (the repo's style; oxfmt does not touch generated files). */
function lit(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

/** Render a doc comment, or nothing when there is nothing to say. */
function doc(lines, indent = '') {
  const body = lines
    .filter((line) => line !== undefined && line !== null && line !== '')
    .flatMap((line) => String(line).split('\n'))
  if (body.length === 0) return ''
  if (body.length === 1) return `${indent}/** ${body[0]} */\n`
  return `${indent}/**\n${body.map((l) => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n`
}

/** A TypeScript type expression for an IR type reference. */
function tsType(ref) {
  const base = (() => {
    switch (ref.kind) {
      case 'string':
        // An OPEN vocabulary (a closed enum plus a `pattern` escape hatch, e.g. a deployment's
        // own `ns:kind` task type). `(string & {})` keeps the literals as editor completions
        // WITHOUT narrowing the type to them — narrowing would make the SDK reject a value the
        // server accepts, which is the one thing a client type must never do.
        return ref.open && ref.suggestedValues?.length
          ? `${ref.suggestedValues.map(lit).join(' | ')} | (string & {})`
          : 'string'
      case 'number':
      case 'integer':
        return 'number'
      case 'boolean':
        return 'boolean'
      case 'const':
        return typeof ref.value === 'string' ? lit(ref.value) : JSON.stringify(ref.value)
      case 'ref':
        return ref.name
      case 'array': {
        const inner = tsType(ref.items)
        return `${inner.includes('|') ? `(${inner})` : inner}[]`
      }
      case 'map':
        return `Record<string, ${tsType(ref.values)}>`
      default:
        return 'unknown'
    }
  })()
  return ref.nullable ? `${base} | null` : base
}

/** SCREAMING_SNAKE constant name for an enum's value list. */
function valuesConstName(typeName) {
  return `${typeName.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()}_VALUES`
}

function emitEnum(type) {
  const literals = type.values.map(lit)
  return (
    `export type ${type.name} = ${literals.join(' | ')}\n\n` +
    doc([`Every \`${type.name}\` value, for exhaustive handling and runtime validation.`]) +
    `export const ${valuesConstName(type.name)} = [${literals.join(', ')}] as const\n`
  )
}

function emitUnion(type) {
  const notes = type.discriminator ? [`Discriminated by \`${type.discriminator.property}\`.`] : []
  return (
    doc(notes) +
    `export type ${type.name} =\n${type.variants.map((v) => `  | ${tsType(v)}`).join('\n')}\n`
  )
}

/** Per-field doc notes that carry information the type itself cannot. */
function fieldNotes(field) {
  const notes = [field.doc]
  if (field.nullable && field.required) {
    notes.push('Always present; `null` when the server has no value for it.')
  }
  const { minimum, maximum, minLength, maxLength } = field.constraints ?? {}
  if (minLength !== undefined || maxLength !== undefined) {
    notes.push(`Length ${minLength ?? 0}..${maxLength ?? '∞'}.`)
  }
  if (minimum !== undefined || maximum !== undefined) {
    notes.push(`Range ${minimum ?? '-∞'}..${maximum ?? '∞'}.`)
  }
  return notes
}

function emitObject(type) {
  const fields = type.fields.map((field) => {
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(field.wireName)
      ? field.wireName
      : lit(field.wireName)
    return `${doc(fieldNotes(field), '  ')}  ${key}${field.required ? '' : '?'}: ${tsType(field.type)}\n`
  })
  return `export interface ${type.name} {\n${fields.join('')}}\n`
}

function emitModels(ir) {
  const blocks = ir.types.map((type) => {
    if (type.kind === 'enum') return emitEnum(type)
    if (type.kind === 'union') return emitUnion(type)
    return emitObject(type)
  })
  return `${BANNER}
// Wire models for the cat-factory public API (\`/api/v1\`), surface version ${ir.info.version}.
//
// A field declared \`T | null\` is ALWAYS SENT and may hold null; a field declared \`?\` may be
// absent entirely. The two are kept apart on purpose — "the server said null" and "the server
// said nothing" are different facts, and a caller that cannot tell them apart cannot report
// either one honestly.

${blocks.join('\n')}`
}

/** The generated query-options interface name for an operation, or null when it takes none. */
function queryTypeName(operation) {
  return operation.queryParams.length > 0
    ? `${pascal(operation.group)}${pascal(operation.method)}Query`
    : null
}

function emitQueryTypes(placed) {
  return placed
    .filter((operation) => operation.queryParams.length > 0)
    .map((operation) => {
      const fields = operation.queryParams
        .map(
          (param) =>
            `${doc([param.doc], '  ')}  ${param.wireName}${param.required ? '' : '?'}: ${tsType(param.type)}\n`,
        )
        .join('')
      // A type ALIAS, not an interface. Only an alias of an object literal gets TypeScript's
      // implicit index signature, which is what lets the transport accept it as a
      // `Record<string, unknown>` query bag — an interface would fail to assign, and the fix
      // would otherwise be to widen the transport's own parameter to `object` and lose the
      // typing there instead.
      return (
        doc([`Query parameters for \`client.${operation.group}.${operation.method}()\`.`]) +
        `export type ${queryTypeName(operation)} = {\n${fields}}\n`
      )
    })
    .join('\n')
}

/** The path template as a TS template literal over the operation's path parameters. */
function pathExpression(operation) {
  const interpolated = operation.path.replace(
    /\{(\w+)\}/g,
    (_m, name) => `\${encodePathSegment(${camel(name)})}`,
  )
  return `\`${interpolated}\``
}

function returnType(operation) {
  if (operation.stream) return 'EventStream'
  if (!operation.result) return 'void'
  return tsType(operation.result)
}

function emitMethod(operation) {
  const query = queryTypeName(operation)
  const params = [
    ...operation.pathParams.map((p) => `${camel(p.wireName)}: string`),
    operation.body ? `body: ${tsType(operation.body)}` : null,
    query ? `query: ${query} = {}` : null,
    'options: RequestOptions = {}',
  ].filter(Boolean)

  const requestFields = [
    `method: ${lit(operation.httpMethod)}`,
    `path: ${pathExpression(operation)}`,
    operation.body ? 'body' : null,
    query ? 'query' : null,
    'options',
  ].filter(Boolean)

  const call = operation.stream
    ? 'this.#transport.stream'
    : operation.result
      ? `this.#transport.request<${tsType(operation.result)}>`
      : 'this.#transport.requestNoContent'

  const notes = [
    operation.summary,
    '',
    operation.description,
    '',
    `\`${operation.httpMethod} ${operation.path}\` — operation \`${operation.id}\`.`,
  ]
  const body = `    return ${call}({\n${requestFields.map((f) => `      ${f},`).join('\n')}\n    })`
  return `${doc(notes, '  ')}  ${operation.method}(${params.join(', ')}): Promise<${returnType(operation)}> {\n${body}\n  }\n`
}

/**
 * An auto-paging async iterator over a keyset-paginated list. Generated only for the
 * operations the surface table marks `paginates`, because the item property differs per
 * endpoint and a caller should not have to know it — nor have to remember that a page whose
 * `nextCursor` is null is the last one.
 */
function emitPager(operation) {
  const query = queryTypeName(operation)
  // The yielded item type is read off the list response's OWN property rather than named
  // separately, so it cannot drift from what the endpoint actually returns.
  const listTypeName = tsType(operation.result)
  const params = [
    ...operation.pathParams.map((p) => `${camel(p.wireName)}: string`),
    query ? `query: ${query} = {}` : null,
    'options: RequestOptions = {}',
  ].filter(Boolean)
  const callArgs = [
    ...operation.pathParams.map((p) => camel(p.wireName)),
    query ? '{ ...query, cursor }' : null,
    'options',
  ].filter(Boolean)
  return (
    doc(
      [
        `Every \`${operation.paginates}\` across every page of \`${operation.method}()\`.`,
        '',
        'Follows `nextCursor` until the server reports no further page. The cursor is opaque',
        "and carries a position, never authority — each page re-applies the key's full scope.",
      ],
      '  ',
    ) +
    `  async *${operation.method}All(${params.join(', ')}): AsyncGenerator<${listTypeName}['${operation.paginates}'][number]> {\n` +
    `    let cursor: string | undefined = ${query ? 'query.cursor' : 'undefined'}\n` +
    '    for (;;) {\n' +
    `      const page = await this.${operation.method}(${callArgs.join(', ')})\n` +
    `      for (const item of page.${operation.paginates}) yield item\n` +
    '      if (!page.nextCursor) return\n' +
    '      if (page.nextCursor === cursor) throw repeatedCursorError()\n' +
    '      cursor = page.nextCursor\n' +
    '    }\n' +
    '  }\n'
  )
}

function emitResource(placed, group) {
  const operations = groupOperations(placed, group)
  const className = `${pascal(group)}Resource`
  const methods = operations.flatMap((operation) => [
    emitMethod(operation),
    operation.paginates ? emitPager(operation) : null,
  ])
  // A declared field plus an assignment, NOT a TypeScript parameter property. A parameter
  // property is one of the few TS constructs that EMITS code rather than erasing, so it cannot be
  // stripped — it breaks Node's `--experimental-strip-types`, `erasableSyntaxOnly` builds, and any
  // consumer vendoring these sources. Everything this generator emits stays erasable.
  return (
    doc([GROUP_DOCS[group]]) +
    `export class ${className} {\n` +
    '  readonly #transport: Transport\n\n' +
    `  constructor(transport: Transport) {\n    this.#transport = transport\n  }\n\n` +
    methods.filter(Boolean).join('\n') +
    '}\n'
  )
}

function emitOperations(ir, placed) {
  const queryTypes = emitQueryTypes(placed)
  const resources = GROUPS.map((group) => emitResource(placed, group)).join('\n')
  // Import exactly the models the emitted text names. A blanket import of all 118 would
  // typecheck but reads as noise and trips `noUnusedLocals` in a consumer's strict build.
  const referenced = ir.types
    .map((t) => t.name)
    .filter((name) => new RegExp(`\\b${name}\\b`).test(queryTypes + resources))
    .sort()
  return `${BANNER}
// The resource clients: one class per resource group, each a thin, typed shell over the
// hand-written \`Transport\`. Nothing here decides retry, auth, error mapping or stream framing —
// that is \`http.ts\` / \`errors.ts\` / \`sse.ts\`, so those can change without touching 38 methods.

import type { EventStream } from './sse.ts'
import type { RequestOptions, Transport } from './http.ts'
import { encodePathSegment } from './http.ts'
import { repeatedCursorError } from './errors.ts'
import type {
${referenced.map((n) => `  ${n},`).join('\n')}
} from './models.generated.ts'

${queryTypes}
${resources}
/**
 * The resource clients a \`CatFactoryClient\` exposes, one per tag of the published OpenAPI surface.
 *
 * Generated and INHERITED by the client rather than re-listed on it: a resource group added to the
 * SDK surface table would otherwise generate, compile, and simply not be reachable from the client
 * anyone actually constructs. (A declaration-merged interface would do the same job, but TypeScript
 * cannot see that such properties are initialised — so a real base class it is.)
 */
export abstract class CatFactoryResources {
${GROUPS.map((g) => `  /** ${GROUP_DOCS[g]} */\n  readonly ${g}: ${pascal(g)}Resource`).join('\n')}

  protected constructor(transport: Transport) {
${GROUPS.map((g) => `    this.${g} = new ${pascal(g)}Resource(transport)`).join('\n')}
  }
}
`
}

/** Every generated file for the TypeScript SDK, keyed by path within `sdk/typescript/`. */
export function emit(ir, placed) {
  return {
    'src/models.generated.ts': emitModels(ir),
    'src/operations.generated.ts': emitOperations(ir, placed),
  }
}
