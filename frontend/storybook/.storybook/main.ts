import type { StorybookConfig } from '@storybook-vue/nuxt'

// Storybook runs STANDALONE (`pnpm storybook`), not as a Nuxt module. Adding `@nuxtjs/storybook`
// to `nuxt.config` would boot Storybook inside `nuxt dev` at `/_storybook`, which changes the
// ordinary dev server for everyone and runs a second Vite server in the same process (a known
// source of plugin-instance corruption, nuxt-modules/storybook#1072). The framework preset is
// what renders the stories; the module is not needed for it.
const config: StorybookConfig = {
  framework: { name: '@storybook-vue/nuxt', options: {} },
  stories: ['../../app/app/components/**/*.stories.@(js|ts)'],
  // axe over every story, in both colour modes. This is the browser-based contrast lane the
  // render-snapshot initiative wanted and PR #2260 could not land as regex: text-on-fill contrast
  // is a COMPUTED property, and the line-scoped rules kept growing special cases for variant
  // chains, array `:class` and `@apply`. A real browser resolves all of it.
  //
  // It does not cover the degenerate-hover rule, which needs a hover-and-compare. That half of
  // #2260 is still open.
  addons: ['@storybook/addon-a11y', '@storybook/addon-vitest'],
  // `mockServiceWorker.js`, which msw's browser worker loads to answer a story's API requests
  // (`frontend/app/app/stories/api.ts`). Generated by `msw init`; regenerate it on an msw bump.
  staticDirs: ['./public'],

  async viteFinal(viteConfig) {
    viteConfig.plugins ??= []
    viteConfig.plugins.push({
      // `@nuxt/fonts` KILLS the Storybook process on the first `/_fonts/*` request.
      //
      // It has a Storybook branch (`nuxt.options.buildId === 'storybook'`) that registers a plain
      // Vite middleware calling its h3 handler with a bare `{ path }`. The handler then calls
      // h3's `setResponseHeader(event, …)`, which reads `event.node.res` off undefined and throws
      // out of a middleware nothing is catching, so Node exits. A missing font takes the same
      // path through `createError({ statusCode: 404 })`.
      //
      // The crash only shows when a REAL browser asks for the fonts, which is why it survived
      // every headless check and died the moment a human opened it.
      //
      // So: answer `/_fonts/*` ourselves, first in the chain, and let the typefaces come from the
      // CDN through `preview-head.html` instead. This is a local dev page, not the shipped app,
      // where self-hosting under `/_fonts` is the whole point.
      name: 'catalog:defuse-nuxt-fonts-dev-handler',
      configureServer(server) {
        server.middlewares.stack.unshift({
          route: '/_fonts',
          handle: (_req: unknown, res: { statusCode: number; end: () => void }) => {
            res.statusCode = 404
            res.end()
          },
        })
      },
    })
    return viteConfig
  },
}
export default config
